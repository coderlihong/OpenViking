"""Post-commit image URI rewriting for OpenViking.

Scans markdown files in VikingFS after source commit and rewrites local
image references to viking:// URIs, driven by the ``.image_mappings.json``
sidecars that ``_ingest_local_images`` writes at each document root (the
images themselves are stored next to the markdown file referencing them).
"""

import json
import re
from pathlib import Path
from typing import Any, Dict, Optional, Set

from openviking.indexing.content import draft_sources
from openviking.server.identity import RequestContext
from openviking.storage.viking_fs import get_viking_fs
from openviking_cli.utils import get_logger

logger = get_logger(__name__)

_IMAGE_PATTERN = re.compile(r"!\[([^\]]*)\]\(((?:[^()]|\([^()]*\))+)\)")
_REMOTE_PREFIXES = ("http://", "https://", "data:", "ftp://")

# An <img> tag already carrying a vikingsrc attribute was normalized by a
# previous pass; it must not be wrapped again.
VIKINGSRC_ATTR = "vikingsrc"
_FIGURE_INDENT = "    "

# The normalized citation form OpenViking publishes for every image occurrence:
#
#     <figure>
#         <img src="{original reference}" vikingsrc="viking://{final URI}"/>
#         <figcaption>
#         {VLM caption, filled in by the caption backfill stage}
#         </figcaption>
#     </figure>
#
# ``src`` keeps the authoring-time reference; ``vikingsrc`` is the authoritative
# viking:// URI of the stored bytes, so consumers never chase relative paths.
def wrap_in_figure(src_attr: str, vikingsrc: str, caption: str = "", alt: str = "") -> str:
    attrs = [f'src="{_xml_attr_escape(src_attr)}"']
    if alt.strip():
        attrs.append(f'alt="{_xml_attr_escape(alt)}"')
    attrs.append(f'{VIKINGSRC_ATTR}="{_xml_attr_escape(vikingsrc)}"')
    lines = [
        "<figure>",
        f'{_FIGURE_INDENT}<img {" ".join(attrs)}/>',
    ]
    # A caption is emitted even when still unfilled: the block marks the
    # occurrence so the backfill stage can find it later.
    lines.append(f"{_FIGURE_INDENT}<figcaption>")
    caption = re.sub(r"\n\s*\n", "\n", caption.strip())
    if caption:
        lines.extend(f"{_FIGURE_INDENT}{line}" for line in caption.splitlines())
    lines.append(f"{_FIGURE_INDENT}</figcaption>")
    lines.append("</figure>")
    return "\n".join(lines)


def strip_figcaption_bodies(content: str) -> str:
    """Drop every ``<figcaption>`` body, keeping the empty element.

    The corpus figcaption is untrusted: it is machine-generated upstream and
    frequently wrong (misidentified subjects, fabricated citations). A caption
    reaches the index only when *we* generated it offline, before upload; the
    trusted body is therefore never present at the ingestion boundary. This
    helper is applied there (corpus fetch, or a caller that must discard an
    upstream body) so an untrusted body can neither reach the VLM prompt nor be
    published as the occurrence summary, while the empty element stays as the
    marker the caption stage fills.

    Ingestion of an already-generated corpus must NOT call this: the figcaption
    it carries is the authoritative description.
    """
    if "<figcaption" not in content.lower():
        return content
    return _FIGCAPTION_BODY_RE.sub(
        lambda m: f"{m.group(1)}\n{_FIGURE_INDENT}{m.group(3)}", content
    )


def _xml_attr_escape(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )

# Authored figcaption bodies are discarded on ingest: the corpus captions are
# known to be unreliable (auto-generated, frequently wrong), so the description
# is always regenerated by the VLM from the image plus its chapter context. The
# empty <figcaption> marker is kept so the backfill stage can find the block.
_FIGCAPTION_BODY_RE = re.compile(
    r"(<figcaption\b[^>]*>)(.*?)(</figcaption\s*>)", re.DOTALL | re.IGNORECASE
)

# Sidecar written by MarkdownParser._ingest_local_images at each document root,
# consumed (and deleted) here. Shared so merge/sync code can recognize it.
IMAGE_MAPPINGS_FILENAME = ".image_mappings.json"

# HTML <img src="..."> embeds, common in markdown for sizing control. Shared
# with the parser so ingestion and rewriting see the same references.
HTML_IMG_PATTERN = re.compile(r"""(<img\s[^>]*?src=["'])([^"']+)(["'][^>]*>)""", re.IGNORECASE)
_FENCE_PATTERN = re.compile(r"^(\s{0,3})(`{3,}|~{3,})")
_LIST_ITEM_PATTERN = re.compile(r"^(\s{0,3})([-*+]|\d{1,9}[.)])(\s+)")


def build_artifact_image_mappings(root_dir: Path) -> Dict[str, Dict[str, str]]:
    """Build the sidecar mapping for an already-materialized parser artifact.

    Understanding API artifacts already place each image next to the markdown
    file that references it. Keep this helper deliberately narrower than
    MarkdownParser's local-image ingestion: it records only existing sibling
    files and never copies or renames artifact content.
    """
    root = root_dir.resolve()
    mappings: Dict[str, Dict[str, str]] = {}

    for md_path in root.rglob("*.md"):
        if not md_path.is_file():
            continue
        try:
            content = md_path.read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            logger.warning(f"[image_rewrite] Failed to read artifact markdown: {md_path}")
            continue

        protected = _protected_ranges(content)

        refs = [(match.start(), match.group(2)) for match in _IMAGE_PATTERN.finditer(content)]
        refs.extend((match.start(), match.group(2)) for match in HTML_IMG_PATTERN.finditer(content))

        file_mappings: Dict[str, str] = {}
        md_dir = md_path.parent.resolve()
        for pos, original_ref in refs:
            if any(start <= pos < end for start, end in protected):
                continue

            ref = original_ref.strip()
            if not ref or _is_remote_uri(ref):
                continue

            # Queries/fragments are not part of the local filesystem path, but
            # the exact original reference remains the mapping key used later.
            path_part = re.split(r"[?#]", ref, maxsplit=1)[0]
            ref_path = Path(path_part)
            if not path_part or ref_path.is_absolute():
                continue

            try:
                candidate = (md_dir / ref_path).resolve()
                candidate.relative_to(root)
            except (OSError, ValueError):
                continue

            # The existing sidecar contract stores only the final filename and
            # rewrite_image_uris resolves it beside the markdown file.
            if candidate.parent != md_dir or not candidate.is_file():
                continue

            file_mappings[original_ref] = candidate.name

        if file_mappings:
            mappings[md_path.relative_to(root).as_posix()] = file_mappings

    return mappings


def _is_remote_uri(path: str) -> bool:
    return any(path.startswith(p) for p in _REMOTE_PREFIXES)


def _scheme_sibling(path: str, available_images: Set[str]) -> Optional[str]:
    """The stored sibling an opaque scheme reference (``kb://images/<id>``) names.

    The authored reference is an identifier, not a path: the bytes sit beside
    the markdown under ``images/`` carrying their real extension. The identifier
    must match whole (exact name, or same stem plus one extension), so a scheme
    reference can never pin a figure to an unrelated file.
    """
    relative = path.split("://", 1)[1].lstrip("/")
    if not relative:
        return None
    if relative in available_images:
        return relative
    prefix = relative + "."
    matches = sorted(
        name
        for name in available_images
        if name.startswith(prefix) and "/" not in name[len(prefix):]
    )
    return matches[0] if matches else None


def _inline_code_ranges(line: str):
    """Yield (start, end) offsets of inline code spans within a single line.

    A code span is a run of N backticks closed by another run of exactly N
    backticks. Unterminated runs are not treated as code.
    """
    i = 0
    n = len(line)
    while i < n:
        if line[i] != "`":
            i += 1
            continue
        j = i
        while j < n and line[j] == "`":
            j += 1
        run = j - i
        k = j
        closed = False
        while k < n:
            if line[k] != "`":
                k += 1
                continue
            m = k
            while m < n and line[m] == "`":
                m += 1
            if m - k == run:
                yield (i, m)
                i = m
                closed = True
                break
            k = m
        if not closed:
            i = j


def _protected_ranges(content: str):
    """Compute character ranges that must not be rewritten.

    Covers fenced code blocks, indented code blocks and inline code spans so
    that Markdown image examples inside code are left untouched.
    """
    ranges = []
    offset = 0
    in_fence = False
    fence_char = ""
    fence_len = 0
    in_indent_code = False
    in_list = False
    prev_blank = True  # start of document behaves like "after a blank line"

    for line in content.splitlines(keepends=True):
        start = offset
        end = offset + len(line)
        offset = end

        line_content = line.rstrip("\n").rstrip("\r")
        stripped = line_content.strip()
        is_blank = stripped == ""

        if in_fence:
            ranges.append((start, end))
            m = _FENCE_PATTERN.match(line_content)
            if (
                m
                and m.group(2)[0] == fence_char
                and len(m.group(2)) >= fence_len
                and stripped == m.group(2)
            ):
                in_fence = False
            prev_blank = is_blank
            continue

        m = _FENCE_PATTERN.match(line_content)
        if m:
            in_fence = True
            in_indent_code = False
            fence_char = m.group(2)[0]
            fence_len = len(m.group(2))
            ranges.append((start, end))
            prev_blank = is_blank
            continue

        indent_width = 0
        for ch in line_content:
            if ch == " ":
                indent_width += 1
            elif ch == "\t":
                indent_width += 4
            else:
                break

        # Track list scope: a list item opens a list; it stays open across
        # blank lines and indented continuation, and closes when a non-blank,
        # non-list line returns to the left margin.
        if _LIST_ITEM_PATTERN.match(line_content):
            in_list = True
        elif in_list and not is_blank and indent_width == 0:
            in_list = False

        if in_indent_code:
            if is_blank or indent_width >= 4:
                ranges.append((start, end))
                prev_blank = is_blank
                continue
            in_indent_code = False
        elif not in_list and not is_blank and indent_width >= 4 and prev_blank:
            in_indent_code = True
            ranges.append((start, end))
            prev_blank = is_blank
            continue

        for s, e in _inline_code_ranges(line_content):
            ranges.append((start + s, start + e))

        prev_blank = is_blank

    return ranges


async def _discover_mappings(
    viking_fs,
    root_prefix: str,
    md_uris: list,
    ctx: Optional[RequestContext] = None,
) -> Dict[str, Dict[str, Dict[str, str]]]:
    """Locate every ``.image_mappings.json`` under *root_prefix*.

    ``_ingest_local_images`` writes one sidecar per document root, and all of a
    document's markdown files live under that root — so probing the ancestor
    directories of the markdown files finds every sidecar regardless of how
    deep the ingest placed the document (single-file ingest leaves it at the
    resource root; directory ingest nests it per document).

    Returns ``{mapping_dir: {rel_md_path: {original_path: image_filename}}}``
    where ``rel_md_path`` is relative to ``mapping_dir``.
    """
    candidates = set()
    for md_uri in md_uris:
        d = md_uri.rsplit("/", 1)[0]
        while d == root_prefix or d.startswith(root_prefix + "/"):
            candidates.add(d)
            if d == root_prefix:
                break
            d = d.rsplit("/", 1)[0]

    found: Dict[str, Dict[str, Dict[str, str]]] = {}
    for d in candidates:
        try:
            content = await viking_fs.read_file(f"{d}/{IMAGE_MAPPINGS_FILENAME}", ctx=ctx)
            found[d] = json.loads(content)
        except Exception:
            continue
    return found


async def rewrite_image_uris(
    root_uri: str,
    ctx: Optional[RequestContext] = None,
    lease_ref: Optional[Dict[str, Any]] = None,
) -> Dict[str, int]:
    """Normalize every image occurrence under *root_uri* into figure form.

    Runs inside a draft-source read context: once content has been published,
    reads of a published URI are served the last published revision, so a
    re-ingest of an existing branch would otherwise rewrite (and then publish)
    the stale revision instead of the bytes just copied into the working tree.
    """
    with draft_sources():
        return await _rewrite_image_uris_inner(root_uri, ctx=ctx, lease_ref=lease_ref)


async def _rewrite_image_uris_inner(
    root_uri: str,
    ctx: Optional[RequestContext] = None,
    lease_ref: Optional[Dict[str, Any]] = None,
) -> Dict[str, int]:
    """Scan all ``.md`` files under *root_uri* and wrap each image
    reference in a ``<figure>`` block whose ``vikingsrc`` attribute carries the
    full viking:// URI of the stored bytes. Two layouts are covered:

    - sidecar layout: references recorded in the ``.image_mappings.json``
      sidecars written by ``_ingest_local_images`` (one per document root,
      holding ``{rel_md_path -> {original_path -> image_filename}}``); each
      sidecar is interpreted in the coordinate system of the directory holding
      it, so both single-file ingest (sidecar at the resource root) and
      directory ingest (sidecar per document subdirectory) are covered.
    - chapter layout: relative ``images/<name>`` references resolved against a
      sibling ``images/`` directory written by ``_apply_chapter_layout``.

    Args:
        root_uri: The final VikingFS root URI (e.g. ``viking://resources/doc``)
        ctx: Optional request context for permissions
        lease_ref: Optional lease reference held by the caller. When the caller
            already owns a TREE lock over *root_uri*, forwarding it lets the
            cleanup ``rm`` reuse that lock instead of conflicting with it.

    Returns:
        Dict with ``files_processed`` and ``references_rewritten`` counts.
    """
    viking_fs = get_viking_fs()

    root_prefix = root_uri.rstrip("/")

    # Find all .md files recursively
    glob_result = await viking_fs.glob("**/*.md", uri=root_uri, ctx=ctx)
    md_uris = glob_result.get("matches", [])

    if not md_uris:
        return {
            "files_processed": 0,
            "references_rewritten": 0,
            "images_materialized": 0,
            "references_unresolved": 0,
        }

    mappings_by_dir = await _discover_mappings(viking_fs, root_prefix, md_uris, ctx)
    fetch_remote, remote_timeout = _remote_fetch_policy()

    files_processed = 0
    references_rewritten = 0
    images_materialized = 0
    references_unresolved = 0

    for md_uri in md_uris:
        # Resolve this markdown file's mapping from the sidecar of the document
        # root containing it (the key is relative to that root).
        path_to_image_name: Dict[str, str] = {}
        for map_dir, file_mappings in mappings_by_dir.items():
            if md_uri.startswith(map_dir + "/"):
                entry = file_mappings.get(md_uri[len(map_dir) + 1 :])
                if entry:
                    path_to_image_name = entry
                    break

        md_dir = md_uri.rsplit("/", 1)[0]

        # Build the set of available images that sit beside this markdown file,
        # including the sibling images/ subtree written by chapter layout.
        available_images: Set[str] = set()
        try:
            entries = await viking_fs.ls(md_dir, ctx=ctx)
            available_images = {
                e["name"] for e in entries if not e.get("isDir") and not e["name"].startswith(".")
            }
            for entry in entries:
                if entry.get("isDir") and entry["name"] == "images":
                    try:
                        img_entries = await viking_fs.ls(f"{md_dir}/images", ctx=ctx)
                        available_images.update(
                            f"images/{e['name']}"
                            for e in img_entries
                            if not e.get("isDir") and not e["name"].startswith(".")
                        )
                    except Exception:
                        logger.debug(f"[image_rewrite] Failed to list {md_dir}/images")
        except Exception:
            logger.debug(f"[image_rewrite] Failed to list directory {md_dir}")

        has_local_refs = any(
            not name.startswith("viking://") for name in available_images
        ) or bool(path_to_image_name)
        if not has_local_refs and not fetch_remote:
            continue

        try:
            content = await viking_fs.read_file(md_uri, ctx=ctx)
        except Exception:
            logger.warning(f"[image_rewrite] Failed to read {md_uri}, skipping")
            continue

        # Authored markdown frequently points its figures at the host that
        # generated the document. Fetch those bytes into a sibling ``images/``
        # directory and rewrite the reference, so what is published resolves to
        # storage OpenViking owns instead of an external URL that may already 404.
        content, stored_names, unresolved = await _materialize_remote_images(
            viking_fs,
            md_dir,
            content,
            ctx=ctx,
            lease_ref=lease_ref,
            enabled=fetch_remote,
            timeout=remote_timeout,
        )
        images_materialized += len(stored_names)
        references_unresolved += unresolved
        available_images.update(f"images/{name}" for name in stored_names)
        if not has_local_refs and not stored_names:
            continue

        new_content, rewrite_count = _rewrite_content(
            content, md_dir, available_images, path_to_image_name
        )

        if rewrite_count > 0:
            try:
                await viking_fs.write_file(
                    md_uri,
                    new_content,
                    ctx=ctx,
                    lease_ref=lease_ref,
                )
                files_processed += 1
                references_rewritten += rewrite_count
                logger.debug(f"[image_rewrite] Rewrote {rewrite_count} image ref(s) in {md_uri}")
            except Exception:
                logger.warning(f"[image_rewrite] Failed to write {md_uri}")

    # Clean up mapping sidecars — no longer needed after rewrite
    for map_dir in mappings_by_dir:
        try:
            await viking_fs.rm(
                f"{map_dir}/{IMAGE_MAPPINGS_FILENAME}",
                ctx=ctx,
                lease_ref=lease_ref,
            )
        except Exception as e:
            logger.warning(
                f"[image_rewrite] Failed to delete {map_dir}/{IMAGE_MAPPINGS_FILENAME}: {e}"
            )

    logger.info(
        f"[image_rewrite] Processed {len(md_uris)} .md files, "
        f"rewrote {references_rewritten} image reference(s) in {files_processed} file(s), "
        f"materialized {images_materialized} remote image(s), "
        f"left {references_unresolved} remote reference(s) unresolved"
    )

    return {
        "files_processed": files_processed,
        "references_rewritten": references_rewritten,
        "images_materialized": images_materialized,
        "references_unresolved": references_unresolved,
    }


def _remote_fetch_policy() -> tuple[bool, float]:
    """Read the markdown parser's remote-asset policy from the live registry.

    A post-commit pass has no parser instance of its own, yet the switch that
    decides whether ingestion may reach an external host belongs to the parser
    configuration — so it is looked up rather than duplicated here. An
    unavailable registry falls back to the documented default (fetch, 20s).
    """
    config = None
    try:
        from openviking.parse.registry import get_registry

        config = get_registry().get_parser_config("markdown")
    except Exception:
        logger.debug("[image_rewrite] Remote asset policy unavailable; using defaults")
    return (
        bool(getattr(config, "fetch_remote_images", True)) if config is not None else True,
        float(getattr(config, "remote_image_timeout", 20.0)) if config is not None else 20.0,
    )


async def _materialize_remote_images(
    viking_fs,
    md_dir: str,
    content: str,
    *,
    ctx: Optional[RequestContext] = None,
    lease_ref: Optional[Dict[str, Any]] = None,
    enabled: bool = True,
    timeout: float = 20.0,
) -> tuple[str, list, int]:
    """Store every fetchable remote figure beside *md_dir* and rewrite its reference.

    Returns ``(content, stored_filenames, unresolved_count)``. An unfetchable
    reference keeps its authored URL: this pass publishes content the user already
    wrote, so it must not delete an occurrence it merely could not resolve (the
    chapter-layout path, which builds a tree from a parse plan, drops instead).
    """
    if not enabled or not content:
        return content, [], 0

    from openviking.parse.remote_images import (
        RemoteImage,
        apply_replacements,
        collect_remote_spans,
        resolve_remote_images,
    )

    spans = collect_remote_spans(content)
    if not spans:
        return content, [], 0

    outcomes = await resolve_remote_images((span[2] for span in spans), timeout=timeout)
    image_dir = f"{md_dir}/images"
    directory_created = False
    replacements = []
    stored: list = []
    unresolved = 0
    for start, end, reference in spans:
        asset = outcomes.get(reference)
        if not isinstance(asset, RemoteImage):
            unresolved += 1
            continue
        if not directory_created:
            await viking_fs.mkdir(image_dir, exist_ok=True, ctx=ctx, lease_ref=lease_ref)
            directory_created = True
        await viking_fs.write_file_bytes(
            f"{image_dir}/{asset.filename}", asset.data, ctx=ctx, lease_ref=lease_ref
        )
        stored.append(asset.filename)
        replacements.append((start, end, f"images/{asset.filename}"))
    return apply_replacements(content, replacements), stored, unresolved


def _rewrite_content(
    content: str,
    image_dir: str,
    available_images: Set[str],
    path_to_image_name: Optional[Dict[str, str]] = None,
) -> tuple[str, int]:
    """Normalize every image occurrence into ``<figure>`` citation form.

    Markdown embeds (``![alt](path)``) and bare ``<img src>`` tags are wrapped:

        <figure>
            <img src="{original}" vikingsrc="viking://{stored URI}"/>
            <figcaption></figcaption>
        </figure>

    ``src`` keeps the authoring-time reference; ``vikingsrc`` points at the
    image bytes stored beside the markdown file. References that cannot be
    materialized (unmapped local paths, remote URLs) pass through untouched,
    as do fenced/code contexts. Already-normalized tags (carrying a
    vikingsrc attribute) are skipped, making the pass idempotent.

    Any ``<figcaption>`` body already present is preserved verbatim: the
    figcaption is the authoritative description, generated offline before
    upload. Untrusted upstream bodies are discarded at the corpus boundary
    (see :func:`strip_figcaption_bodies`), never here — discarding them at
    ingestion would wipe the trusted caption too.

    Returns (new_content, normalized_count).
    """
    rewrite_count = 0
    mappings = path_to_image_name or {}

    protected = _protected_ranges(content)

    def _in_protected(pos: int) -> bool:
        for s, e in protected:
            if s <= pos < e:
                return True
        return False

    def _figure_for(src_attr: str, vikingsrc: str, alt: str = "") -> str:
        nonlocal rewrite_count
        rewrite_count += 1
        return wrap_in_figure(src_attr, vikingsrc, alt=alt)

    def replacer(match: re.Match) -> str:
        alt_text = match.group(1)
        path = match.group(2)

        if _in_protected(match.start()):
            return match.group(0)
        if any(path.startswith(p) for p in ("http://", "https://", "data:", "ftp://")):
            return match.group(0)

        if path.startswith("viking://"):
            return _figure_for(path, path, alt=alt_text)

        uri = _mapped_uri(path)
        if uri is None:
            return match.group(0)
        return _figure_for(path, uri, alt=alt_text)

    def img_tag_replacer(match: re.Match) -> str:
        nonlocal rewrite_count
        tag = match.group(0)
        path = match.group(2)

        if _in_protected(match.start()):
            return tag
        if f"{VIKINGSRC_ATTR}=" in tag:
            return tag
        if any(path.startswith(p) for p in ("http://", "https://", "data:", "ftp://")):
            return tag

        if path.startswith("viking://"):
            uri = path
        else:
            uri = _mapped_uri(path)
            if uri is None:
                return tag

        rewrite_count += 1
        # Keep the authoring tag (sizing attrs etc.) and append the pointer
        # attribute before the closing bracket.
        attr = f' {VIKINGSRC_ATTR}="{_xml_attr_escape(uri)}"'
        if tag.rstrip().endswith("/>"):
            inner = tag.rstrip()[:-2].rstrip()
            return f"{inner}{attr}/>"
        return f"{tag[:-1]}{attr}>"

    def _mapped_uri(path: str) -> Optional[str]:
        """viking:// URI for *path* if the mapping covers it, else None."""
        image_name = mappings.get(path)
        if image_name and image_name in available_images:
            return f"{image_dir}/{image_name}"
        if "://" in path:
            stored = _scheme_sibling(path, available_images)
            if stored is not None:
                return f"{image_dir}/{stored}"
            logger.warning(
                f"[image_rewrite] Scheme reference has no stored sibling: path = {path}, "
                f"image_dir = {image_dir}, leaving reference unchanged"
            )
            return None
        # Chapter layout publishes references as images/<name> with no sidecar;
        # the sibling listing is authoritative there.
        stripped = path.lstrip("./")
        if path != stripped and stripped in available_images:
            return f"{image_dir}/{stripped}"
        if path in available_images:
            return f"{image_dir}/{path}"
        logger.warning(
            f"[image_rewrite] Image not found in VikingFS: path = {path}, "
            f"image_dir = {image_dir}, leaving reference unchanged"
        )
        return None

    # Wrap markdown embeds in figure blocks first. The markdown pass may have
    # shifted offsets, so recompute protected ranges against the updated text
    # before rewriting <img> tags.
    new_content = _IMAGE_PATTERN.sub(replacer, content)
    protected = _protected_ranges(new_content)
    new_content = HTML_IMG_PATTERN.sub(img_tag_replacer, new_content)
    return new_content, rewrite_count
